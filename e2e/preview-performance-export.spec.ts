import { expect, test } from './fixtures'

test('新規読込はタイルを表示し、全体表示の状態も保持する', async ({ page }, testInfo) => {
  await page.goto('./')
  await page.getByRole('button', { name: 'サンプルデータで試す', exact: true }).click()
  await expect(page.getByTestId('tiled-preview')).toBeVisible()
  await page.getByRole('button', { name: '全体プレビュー', exact: true }).click()
  const whole = page.getByTestId('navigator-view')
  await expect(whole).toBeVisible()
  await expect.poll(() => whole.locator('canvas').evaluate((canvas: HTMLCanvasElement) => canvas.width)).toBeGreaterThan(1)
  await expect(page.getByTestId('navigator-panel')).toHaveCount(0)
  const tree = page.getByTestId('layer-tree')
  const before = await tree.boundingBox()
  await whole.locator('canvas').hover()
  await page.mouse.wheel(0, -100)
  const transform = await whole.locator('canvas').evaluate(canvas => canvas.style.transform)
  await page.getByRole('listbox', { name: '出力ファイル' }).getByRole('option', { name: 'B_1.jpg', exact: true }).click()
  await expect(page.getByTestId('preview-file-name')).toHaveText('B_1.jpg')
  // Hidden canvases release their backing storage while retaining zoom state.
  await expect.poll(() => whole.locator('canvas').evaluate((canvas: HTMLCanvasElement) => canvas.width)).toBe(1)
  await page.getByRole('button', { name: '全体プレビュー', exact: true }).click()
  expect(await whole.locator('canvas').evaluate(canvas => canvas.style.transform)).toBe(transform)
  expect(await tree.boundingBox()).toEqual(before)
  await page.getByRole('button', { name: '出力プレビュー', exact: true }).click()
  await page.locator('input[type=file][multiple]').setInputFiles('public/sample/c001.clip')
  await expect(page.getByTestId('tiled-preview')).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('whole-preview.png') })
})

test('通常書き出しは進捗とファイル名を示して操作を止め、終了時に自動解除する', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 1280, height: 820 })
  await page.addInitScript(() => {
    Object.defineProperty(window, 'showSaveFilePicker', { configurable: true, value: undefined })
    Object.defineProperty(window, 'showDirectoryPicker', { configurable: true, value: undefined })
    const original = HTMLCanvasElement.prototype.toBlob
    HTMLCanvasElement.prototype.toBlob = function (callback, ...args) {
      original.call(this, blob => setTimeout(() => callback(blob), 100), ...args)
    }
  })
  await page.goto('./')
  await page.getByRole('button', { name: 'サンプルデータで試す', exact: true }).click()
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: '出力', exact: true }).click()
  const status = page.getByTestId('export-status')
  await expect(page.locator('.app-workspace')).toHaveAttribute('inert', '')
  await expect(status.getByRole('progressbar')).toBeVisible()
  await expect(status).toContainText('.jpg')
  await page.keyboard.press('Control+z')
  await page.getByRole('button', { name: '全体プレビュー', exact: true, includeHidden: true }).dispatchEvent('click')
  await page.locator('input[type=file][multiple]').setInputFiles({ name: 'blocked.clip', mimeType: 'application/octet-stream', buffer: Buffer.from('invalid') })
  await page.screenshot({ path: testInfo.outputPath('export-progress.png') })
  expect((await download).suggestedFilename()).toBe('c001.zip')
  await expect(status).toHaveAttribute('data-phase', 'done')
  await expect(page.locator('.app-workspace')).not.toHaveAttribute('inert', '')
  await expect(page.getByRole('button', { name: 'エラーの詳細' })).toHaveCount(0)
  await page.getByRole('listbox', { name: '出力ファイル' }).getByRole('option', { name: 'B_1.jpg', exact: true }).click()
  await expect(page.getByTestId('preview-file-name')).toHaveText('B_1.jpg')
  await expect(status).toHaveCount(0, { timeout: 8000 })
})

test('保存先キャンセルと保存失敗のどちらでも操作ロックを解除する', async ({ page }) => {
  await page.addInitScript(() => {
    Object.defineProperty(window, 'showDirectoryPicker', { configurable: true, value: undefined })
    Object.defineProperty(window, 'showSaveFilePicker', { configurable: true, value: async () => { throw new DOMException('cancel', 'AbortError') } })
  })
  await page.goto('./')
  await page.getByRole('button', { name: 'サンプルデータで試す', exact: true }).click()
  await page.getByRole('button', { name: '出力', exact: true }).click()
  await expect(page.getByTestId('export-status')).toHaveAttribute('data-phase', 'cancelled')
  await expect(page.locator('.app-workspace')).not.toHaveAttribute('inert', '')
  await page.evaluate(() => Object.defineProperty(window, 'showSaveFilePicker', { configurable: true, value: async () => ({ createWritable: async () => new WritableStream({ write() { throw new Error('保存テストエラー') } }) }) }))
  await page.getByRole('button', { name: '出力', exact: true }).click()
  await expect(page.getByTestId('export-status')).toHaveAttribute('data-phase', 'error')
  await expect(page.getByTestId('export-status')).toContainText('保存テストエラー')
  await expect(page.locator('.app-workspace')).not.toHaveAttribute('inert', '')
  await page.getByRole('button', { name: '出力プレビュー', exact: true }).click()
  await expect(page.getByTestId('output-view')).toBeVisible()
})
