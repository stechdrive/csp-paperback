import { expect, test, type Page } from './fixtures'

async function openDetails(page: Page) {
  await page.getByRole('button', { name: '書き出し設定', exact: true }).click()
  await page.getByRole('button', { name: '詳細設定…', exact: true }).click()
  return page.getByRole('dialog', { name: '書き出し詳細設定', exact: true })
}

test('名前の確定・取消・Undoとヘルプ往復で、出力と設定位置を保つ', async ({ page }) => {
  await page.goto('./')
  await page.getByRole('button', { name: 'サンプルデータで試す', exact: true }).click()
  const files = page.getByRole('listbox', { name: '出力ファイル' })
  await expect(files.getByRole('option')).toHaveCount(9)
  await expect(files).toHaveAttribute('aria-busy', 'false')
  const originalFiles = await files.getByRole('option').allTextContents()
  const details = await openDetails(page)
  const name = details.getByLabel('工程に属さないセル画像のグループ名')
  await name.fill('取り消す名前')
  await name.press('Escape')
  await expect(name).toHaveValue('作画')
  await expect(details).toBeVisible()
  await name.fill('  原画  ')
  await name.press('Enter')
  await expect(name).toHaveValue('原画')

  for (const [label, tab] of [['工程の分け方を見る', /機能ガイド/], ['各社テンプレートの例を見る', /各社テンプレートへの対応/]] as const) {
    const link = details.getByRole('button', { name: label })
    await link.scrollIntoViewIfNeeded()
    const body = details.locator('[class*="_body_"]')
    const scroll = await body.evaluate(el => el.scrollTop)
    await link.click()
    const help = page.getByRole('dialog', { name: 'CSP Paperback ヘルプ' })
    await expect(help.getByRole('tab', { name: tab })).toHaveAttribute('aria-selected', 'true')
    if (label === '工程の分け方を見る') {
      await expect(help.getByRole('heading', { name: '9. 演出・作監などの修正工程を分けて出力する' })).toBeInViewport()
    }
    await page.keyboard.press('Escape')
    await expect(help).toHaveCount(0)
    await expect(link).toBeFocused()
    expect(await body.evaluate(el => el.scrollTop)).toBe(scroll)
    await expect(name).toHaveValue('原画')
  }
  await details.getByRole('button', { name: '完了', exact: true }).click()
  expect(await files.getByRole('option').allTextContents()).toEqual(originalFiles)
  // Enter followed by blur/close must create only one application Undo entry.
  await page.getByRole('button', { name: '元に戻す', exact: true }).click()
  let settings = await openDetails(page)
  await expect(settings.getByLabel('工程に属さないセル画像のグループ名')).toHaveValue('作画')
  await settings.getByRole('button', { name: '完了', exact: true }).click()
  await page.getByRole('button', { name: 'やり直し', exact: true }).click()
  settings = await openDetails(page)
  await expect(settings.getByLabel('工程に属さないセル画像のグループ名')).toHaveValue('原画')
  await settings.getByLabel('工程に属さないセル画像のグループ名').fill('動画')
  await settings.getByRole('button', { name: '完了', exact: true }).click()
  await page.reload()
  await page.getByRole('button', { name: '書き出し設定', exact: true }).click()
  await expect(page.getByRole('group', { name: '出力対象' }).getByRole('button', { name: '動画', exact: true })).toBeVisible()
})

test.describe('狭い画面の工程設定', () => {
  test.use({ viewport: { width: 390, height: 900 }, hasTouch: true, isMobile: true })
  test('長い名前でも横にあふれず、列の説明とヘルプをタッチで開ける', async ({ page }, info) => {
    await page.goto('./')
    const details = await openDetails(page)
    const name = details.getByLabel('工程に属さないセル画像のグループ名')
    const longName = '作品で使用する工程に属さないセル画像のグループ名'.repeat(3)
    await name.fill(longName)
    await name.press('Tab')
    await details.getByRole('button', { name: 'フォルダ名（カンマ区切り）の説明', exact: true }).tap()
    await expect(page.getByRole('tooltip')).toContainText('素材内でこの工程として扱うフォルダ名')
    await page.keyboard.press('Escape')
    await details.getByRole('button', { name: '各社テンプレートの例を見る' }).tap()
    const help = page.getByRole('dialog', { name: 'CSP Paperback ヘルプ' })
    await expect(help.getByRole('tab', { name: /各社テンプレートへの対応/ })).toHaveAttribute('aria-selected', 'true')
    await help.getByRole('button', { name: 'ヘルプを閉じる' }).tap()
    await name.scrollIntoViewIfNeeded()
    await expect(name).toHaveValue(longName)
    expect(await details.locator('[class*="_body_"]').evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
    await page.screenshot({ path: info.outputPath('process-settings-mobile.png') })
    await details.getByRole('button', { name: '完了', exact: true }).tap()
    await page.getByRole('button', { name: '書き出し設定', exact: true }).tap()
    const targets = page.getByRole('group', { name: '出力対象' })
    await expect(targets.getByRole('button', { name: longName, exact: true })).toBeVisible()
    expect(await targets.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
  })
})
