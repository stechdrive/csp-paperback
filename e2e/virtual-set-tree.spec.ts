import { initializeCanvas, writePsdBuffer } from 'ag-psd'
import { createCanvas } from '@napi-rs/canvas'
import { test, expect, type Locator, type Page } from './fixtures'

function fixture() {
  initializeCanvas((w, h) => createCanvas(w, h) as unknown as HTMLCanvasElement)
  const layer = (name: string, color: string) => {
    const canvas = createCanvas(24, 24), ctx = canvas.getContext('2d')
    ctx.fillStyle = color; ctx.fillRect(0, 0, 24, 24)
    return { name, opacity: 1, canvas: canvas as unknown as HTMLCanvasElement }
  }
  return { name: 'virtual-tree.psd', mimeType: 'application/octet-stream', buffer: writePsdBuffer({ width: 24, height: 24,
    children: [layer('追加B', '#00ff00'), layer('追加A', '#ff0000'), { name: '空フォルダ', children: [] },
      { name: 'フォルダ', blendMode: 'normal', children: [layer('下の素材', '#ffffff'), layer('上の素材', '#0000ff')] },
      layer('先頭', '#000000')],
  }, { noBackground: true }) }
}

async function setup(page: Page) {
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('./')
  await page.locator('input[type=file][multiple]').setInputFiles(fixture())
  await expect(page.getByTestId('layer-tree').getByText('先頭', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '仮想セル', exact: true }).click()
  await page.getByRole('button', { name: '＋ 追加', exact: true }).click()
  await expect(page.getByRole('button', { name: '仮想セルをプレビュー', exact: true })).toBeInViewport()
  await expect(page.getByRole('button', { name: 'この仮想セルを削除', exact: true })).toBeInViewport()
  const tree = page.getByTestId('virtual-set-tree')
  const source = (name: string) => page.getByTestId('layer-tree').locator('[data-layer-id]').filter({ has: page.getByText(name, { exact: true }) })
  const row = (name: string) => tree.locator('[data-vs-layer-id]').filter({ has: page.getByText(name, { exact: true }) })
  const roots = () => tree.locator(':scope > [data-vs-node-id] > [data-vs-layer-id] [data-layer-name]').allTextContents()
  await source('先頭').dragTo(tree.locator('[data-vs-root-drop]'))
  await source('フォルダ').dragTo(tree.locator('[data-vs-root-drop]'))
  await expect(row('フォルダ')).toBeVisible()
  return { tree, source, row, roots }
}

async function startDrag(page: Page, from: Locator, to: Locator, fraction: number) {
  await from.scrollIntoViewIfNeeded(); await to.scrollIntoViewIfNeeded()
  const a = (await from.boundingBox())!, b = (await to.boundingBox())!
  await page.mouse.move(a.x + Math.min(100, a.width - 8), a.y + a.height / 2)
  await page.mouse.down()
  await page.mouse.move(a.x + Math.min(100, a.width - 8) + 8, a.y + a.height / 2, { steps: 3 })
  await page.mouse.move(b.x + Math.min(90, b.width - 8), b.y + b.height * fraction, { steps: 12 })
  await page.mouse.move(b.x + Math.min(90, b.width - 8) + 1, b.y + b.height * fraction)
}

test('仮想セル内だけ名前を変更でき、キャンセル・日本語入力・Undoを扱える', async ({ page }) => {
  const { tree, source, row } = await setup(page)
  const edit = tree.getByRole('textbox', { name: 'レイヤー名を編集' })
  await row('先頭').getByText('先頭', { exact: true }).dblclick()
  await edit.fill('背景用')
  await edit.press('Enter')
  await expect(row('背景用')).toBeVisible()
  await expect(source('先頭')).toBeVisible()
  await row('背景用').press('F2')
  await edit.fill('取り消し')
  await edit.press('Escape')
  await expect(row('背景用')).toBeVisible()
  await row('フォルダ').click({ button: 'right' })
  await page.getByRole('menuitem', { name: '名前を変更', exact: true }).click()
  await edit.fill('仕上げ')
  await edit.dispatchEvent('keydown', { key: 'Enter', isComposing: true })
  await expect(edit).toBeFocused()
  await edit.press('Enter')
  await expect(row('仕上げ')).toBeVisible()
  await expect(source('フォルダ')).toBeVisible()
  await page.getByRole('button', { name: '元に戻す', exact: true }).click()
  await expect(row('フォルダ')).toBeVisible()
  await page.getByRole('button', { name: 'やり直し', exact: true }).click()
  await expect(row('仕上げ')).toBeVisible()
  await row('背景用').press('F2')
  await edit.fill('  ')
  await edit.press('Enter')
  await expect(row('背景用')).toBeVisible()
})

test('新規フォルダに素材を入れ、合成設定と画素を確認して削除・Undoできる', async ({ page }, info) => {
  const { tree, source, row } = await setup(page)
  const panel = page.getByTestId('virtual-panel')
  const edit = tree.getByRole('textbox', { name: 'レイヤー名を編集' })
  await row('フォルダ').click()
  await panel.getByRole('button', { name: '新規レイヤーフォルダ', exact: true }).click()
  await edit.fill('仕上げ')
  await edit.press('Enter')
  await expect(row('仕上げ')).toHaveAttribute('data-vs-depth', '1')
  await source('追加A').dragTo(row('仕上げ'))
  await source('追加B').dragTo(row('仕上げ'))
  await row('仕上げ').click()
  await expect(panel.getByRole('combobox', { name: '合成モード' })).toHaveValue('pass through')
  await panel.getByRole('combobox', { name: '合成モード' }).selectOption('normal')
  await panel.getByRole('button', { name: '不透明度 100%' }).click()
  await panel.getByRole('spinbutton', { name: '不透明度', exact: true }).fill('50')
  await panel.getByRole('spinbutton', { name: '不透明度', exact: true }).press('Enter')
  await page.getByRole('button', { name: '仮想セルの選択素材をクイックルック' }).click()
  const dialog = page.getByRole('dialog', { name: '素材のクイックルック' })
  await expect(dialog).toContainText('仕上げ')
  await expect.poll(() => dialog.locator('canvas').evaluate(canvas => [...(canvas as HTMLCanvasElement).getContext('2d')!.getImageData(12, 12, 1, 1).data])).toEqual([0, 255, 0, 128])
  await page.getByRole('button', { name: 'クイックルックを閉じる' }).click()
  await row('仕上げ').dragTo(row('先頭'), { targetPosition: { x: 90, y: 2 } })
  await expect(row('仕上げ')).toHaveAttribute('data-vs-depth', '0')
  await expect(row('追加A')).toHaveAttribute('data-vs-depth', '1')
  await panel.getByRole('button', { name: '選択した要素を仮想セルから取り除く', exact: true }).click()
  await expect(row('仕上げ')).toHaveCount(0)
  await expect(row('追加A')).toHaveCount(0)
  await expect(source('追加A')).toBeVisible()
  await page.getByRole('button', { name: '元に戻す', exact: true }).click()
  await expect(row('追加A')).toBeVisible()
  await row('仕上げ').click()
  await expect(panel.getByRole('button', { name: '不透明度 50%' })).toBeVisible()
  await expect(panel.getByRole('combobox', { name: '合成モード' })).toHaveValue('normal')
  await page.screenshot({ path: info.outputPath('local-folder.png') })
})

test('ツリー上部の2つのアイコンから作成・選択削除を操作し、一括削除も1回のUndoで戻せる', async ({ page }, info) => {
  const { source, row, roots } = await setup(page)
  const toolbar = page.getByRole('group', { name: '新規仮想セルのレイヤー操作', exact: true })
  const remove = toolbar.getByRole('button', { name: '選択した要素を仮想セルから取り除く', exact: true })
  await expect(toolbar.getByRole('button')).toHaveCount(2)
  await expect(toolbar.getByRole('button')).toHaveText(['', ''])
  const barBox = (await toolbar.boundingBox())!, rowBox = (await row('先頭').boundingBox())!
  expect(barBox.y + barBox.height).toBeLessThanOrEqual(rowBox.y)
  await row('フォルダ').click({ modifiers: ['Control'] })
  await expect(remove).toBeDisabled()
  await row('先頭').click()
  await row('フォルダ').click({ modifiers: ['Control'] })
  await expect(remove).toBeEnabled()
  await remove.click()
  await expect.poll(roots).toEqual([])
  await expect(remove).toBeDisabled()
  await expect(source('先頭')).toBeVisible()
  await expect(source('フォルダ')).toBeVisible()
  await page.getByRole('button', { name: '元に戻す', exact: true }).click()
  await expect.poll(roots).toEqual(['先頭', 'フォルダ'])
  await row('先頭').click()
  await page.locator('[data-virtual-set-card]').screenshot({ path: info.outputPath('tree-toolbar.png') })
})

test('右ツリーから境界・フォルダ内・空フォルダへ追加し、階層移動をUndoできる', async ({ page }, info) => {
  const { tree, source, row, roots } = await setup(page)
  const before = await row('フォルダ').boundingBox()
  await startDrag(page, source('追加A'), row('フォルダ'), .08)
  await expect(tree.locator('[data-vs-insertion="above"]')).toBeVisible()
  expect(await row('フォルダ').boundingBox()).toEqual(before)
  await page.screenshot({ path: info.outputPath('insert-between.png') })
  await page.mouse.up()
  await expect.poll(roots).toEqual(['先頭', '追加A', 'フォルダ'])
  await source('追加B').dragTo(row('フォルダ'))
  await expect(row('追加B')).toHaveAttribute('data-vs-depth', '1')
  await expect(row('上の素材')).toBeVisible()
  await source('空フォルダ').dragTo(row('上の素材'), { targetPosition: { x: 90, y: 2 } })
  await row('追加A').dragTo(row('空フォルダ'))
  await expect(row('追加A')).toHaveAttribute('data-vs-depth', '2')
  await row('追加A').dragTo(row('先頭'), { targetPosition: { x: 90, y: 2 } })
  await expect.poll(roots).toEqual(['追加A', '先頭', 'フォルダ'])
  await page.getByRole('button', { name: '元に戻す', exact: true }).click()
  await expect(row('追加A')).toHaveAttribute('data-vs-depth', '2')
  await page.getByRole('button', { name: 'やり直し', exact: true }).click()
  await expect(row('追加A')).toHaveAttribute('data-vs-depth', '0')
  await row('追加A').click({ button: 'right' })
  await page.getByRole('menuitem', { name: '仮想セルから取り除く', exact: true }).click()
  await expect(row('追加A')).toHaveCount(0)
  await expect(source('追加A')).toBeVisible()
  await expect(source('追加B')).toBeVisible()
  await page.screenshot({ path: info.outputPath('virtual-hierarchy.png') })
})

test('複数選択はツリー順を維持し、閉じたフォルダはドラッグ中に展開する', async ({ page }) => {
  const { tree, source, row, roots } = await setup(page)
  await source('追加A').dragTo(tree.locator('[data-vs-root-drop]'))
  await source('追加B').dragTo(tree.locator('[data-vs-root-drop]'))
  await row('追加B').click()
  await row('追加A').click({ modifiers: ['Control'] })
  await row('追加B').dragTo(row('先頭'), { targetPosition: { x: 90, y: 2 } })
  await expect.poll(roots).toEqual(['追加A', '追加B', '先頭', 'フォルダ'])
  await startDrag(page, row('追加A'), row('フォルダ'), .5)
  await expect(row('フォルダ')).toHaveAttribute('data-vs-drop', 'inside')
  await expect(row('上の素材')).toBeVisible()
  await page.mouse.up()
  await expect(row('追加A')).toHaveAttribute('data-vs-depth', '1')
  await expect(row('追加B')).toHaveAttribute('data-vs-depth', '1')
  const group = row('フォルダ')
  await startDrag(page, group, row('上の素材'), .08)
  await expect(tree.locator('[data-vs-insertion]')).toHaveCount(0)
  await page.mouse.up()
  await expect.poll(roots).toEqual(['先頭', 'フォルダ'])
})

test('デスクトップ用ポインター経路でも追加でき、Escapeで挿入を取り消せる', async ({ page }) => {
  const { tree, source, row, roots } = await setup(page)
  // Exercise the WebView pointer path in Chromium; this is not a native Tauri acceptance test.
  await page.evaluate(() => Object.defineProperty(window, 'isTauri', { configurable: true, value: true }))
  await source('追加A').click()
  await source('追加A').evaluate(element => element.setAttribute('draggable', 'false'))
  await startDrag(page, source('追加A'), row('フォルダ'), .08)
  await expect(tree.locator('[data-vs-insertion="above"]')).toBeVisible()
  await expect(page.locator('[data-layer-drag-preview]')).toBeVisible()
  await page.keyboard.press('Escape')
  await page.mouse.up()
  await expect.poll(roots).toEqual(['先頭', 'フォルダ'])
  await expect(tree.locator('[data-vs-insertion]')).toHaveCount(0)
  await expect(page.locator('[data-layer-drag-preview]')).toHaveCount(0)
  await startDrag(page, source('追加A'), row('フォルダ'), .08)
  await page.mouse.up()
  await expect.poll(roots).toEqual(['先頭', '追加A', 'フォルダ'])
  await row('追加A').dragTo(row('フォルダ'))
  await expect(row('追加A')).toHaveAttribute('data-vs-depth', '1')
  await row('追加A').dragTo(row('先頭'), { targetPosition: { x: 90, y: 2 } })
  await expect.poll(roots).toEqual(['追加A', '先頭', 'フォルダ'])
})
