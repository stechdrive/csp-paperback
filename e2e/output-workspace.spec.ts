import { expect, test, type Page } from '@playwright/test'
import { readFile } from 'node:fs/promises'
import { unzipSync } from 'fflate'

const list = (page: Page) => page.getByRole('listbox', { name: '出力ファイル' })
const file = (page: Page, name: string) => list(page).getByRole('option', { name, exact: true })
const preview = (page: Page) => page.getByTestId('preview-file-name')
const tree = (page: Page) => page.getByTestId('layer-tree')

test.beforeEach(async ({ page }) => {
  await page.setViewportSize({ width: 1280, height: 820 })
  await page.addInitScript(() => {
    Object.defineProperty(window, 'showSaveFilePicker', { configurable: true, value: undefined })
    Object.defineProperty(window, 'showDirectoryPicker', { configurable: true, value: undefined })
  })
  await page.goto('./')
  await page.getByRole('button', { name: 'サンプルデータで試す', exact: true }).click()
  await expect(preview(page)).toHaveText('仮想セルテスト.jpg')
})

test('サムネと合成元を常時示し、素材のQuick Lookは目玉・中央画像・Undoを変更しない', async ({ page }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await file(page, 'B_1_s.jpg').click()
  await expect(preview(page)).toHaveText('B_1_s.jpg')
  await expect(file(page, 'B_1_s.jpg').locator('canvas')).toHaveAttribute('data-ready', 'true')
  await expect(page.getByTestId('output-connections').locator('path').first()).toBeVisible()
  expect(await page.getByTestId('output-connections').evaluate(el => getComputedStyle(el).pointerEvents)).toBe('none')
  const memo = tree(page).locator('[data-layer-id]').filter({ has: page.getByText('memo', { exact: true }) })
  await memo.getByText('memo', { exact: true }).click()
  const eyes = await tree(page).locator('button[aria-pressed]').evaluateAll(buttons => buttons.map(button => button.getAttribute('aria-pressed')))
  await page.keyboard.press('Space')
  const look = page.getByRole('dialog', { name: '素材のクイックルック' })
  await expect(look).toBeVisible()
  await expect(look.locator('canvas')).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('quick-look.png') })
  await page.keyboard.press('Escape')
  await expect(look).toHaveCount(0)
  await expect(tree(page)).toBeFocused()
  await expect(preview(page)).toHaveText('B_1_s.jpg')
  expect(await tree(page).locator('button[aria-pressed]').evaluateAll(buttons => buttons.map(button => button.getAttribute('aria-pressed')))).toEqual(eyes)
  const search = page.getByRole('searchbox')
  await search.fill('A')
  await page.keyboard.press('Space')
  await expect(search).toHaveValue('A ')
  await expect(look).toHaveCount(0)
  await search.fill('')
  await memo.getByRole('button', { name: 'プレビューから非表示にする' }).click()
  await search.fill('memo')
  await page.keyboard.press('Control+z')
  await expect(memo.getByRole('button', { name: 'プレビューに表示する' })).toHaveAttribute('aria-pressed', 'false')
  await search.fill('')
  await tree(page).focus()
  await page.keyboard.press('Control+z')
  await expect(memo.getByRole('button', { name: 'プレビューから非表示にする' })).toHaveAttribute('aria-pressed', 'true')
  expect(errors).toEqual([])
})

test('複数選択・検索・右クリックで全件と同じ名前と画像だけを書き出す', async ({ page }) => {
  const allDownload = page.waitForEvent('download')
  await page.getByRole('button', { name: '出力', exact: true }).click()
  const all = unzipSync(await readFile((await (await allDownload).path())!))
  await file(page, 'B_1.jpg').click()
  await file(page, 'B_1_s.jpg').click({ modifiers: ['Control'] })
  await expect(list(page).getByRole('option', { selected: true })).toHaveCount(2)
  await page.getByRole('searchbox').fill('_1_s')
  await expect(page.getByText('2選択（一覧外1）', { exact: true })).toBeVisible()
  await file(page, 'B_1_s.jpg').click({ button: 'right' })
  const menu = page.getByRole('menu', { name: '選択した出力の操作' })
  await expect(menu).toContainText('2件を書き出し')
  const download = page.waitForEvent('download')
  await menu.getByRole('menuitem', { name: '選択項目をZIPに書き出し' }).click()
  const subset = unzipSync(await readFile((await (await download).path())!))
  expect(Object.keys(subset).sort()).toEqual(['B_1.jpg', 'B_1_s.jpg'])
  for (const [name, bytes] of Object.entries(subset)) expect(Buffer.from(bytes)).toEqual(Buffer.from(all[name]))
  await page.getByRole('searchbox').fill('')
  await file(page, '_PAN.jpg').click({ button: 'right' })
  await expect(menu).toContainText('1件を書き出し')
  await page.keyboard.press('Escape')
  await expect(menu).toHaveCount(0)
  await expect(list(page)).toBeFocused()
  await file(page, 'B_1.jpg').click()
  await file(page, 'A_1.jpg').click({ modifiers: ['Shift'] })
  await expect(list(page).getByRole('option', { selected: true })).toHaveText(['B_1.jpg', 'B_1_s.jpg', 'A_1.jpg'])
})

test('未配置の仮想セルを確認し、素材追加・挿入・解除・Undoでも出力選択を保つ', async ({ page }) => {
  await page.getByRole('button', { name: '仮想セル', exact: true }).click()
  const panel = page.getByTestId('virtual-panel')
  await panel.getByRole('button', { name: /追加/ }).click()
  const item = panel.locator('[class*="_item_"]').last()
  await item.getByRole('textbox').fill('確認用')
  const memo = tree(page).locator('[data-layer-id]').filter({ has: page.getByText('memo', { exact: true }) })
  await page.getByRole('button', { name: 'メニュー', exact: true }).click()
  await memo.dragTo(item.getByText('レイヤーをドロップ', { exact: true }))
  await expect(page.locator('#toolbar-app-menu')).toHaveCount(0)
  await expect(item.getByText('memo', { exact: true })).toBeVisible()
  await expect(list(page)).toContainText('未配置の仮想セル')
  await file(page, '確認用').click()
  await expect(preview(page)).toHaveText('確認用')
  await memo.getByText('memo', { exact: true }).click()
  // Desktop uses the insertion handle; the ↑/↓ alternative is touch-only.
  await item.locator('[class*="_dragHandle_"]').dragTo(memo, { targetPosition: { x: 70, y: 3 } })
  await expect(file(page, '確認用.jpg')).toHaveAttribute('data-active-output', 'true')
  await expect(preview(page)).toHaveText('確認用.jpg')
  await item.getByRole('button', { name: 'クリア', exact: true }).click()
  await expect(file(page, '確認用')).toHaveAttribute('data-active-output', 'true')
  await expect(preview(page)).toHaveText('確認用')
  await tree(page).focus()
  await page.keyboard.press('Control+z')
  await expect(file(page, '確認用.jpg')).toHaveAttribute('data-active-output', 'true')
  await expect(preview(page)).toHaveText('確認用.jpg')
})

test('目玉のなぞりは1回のUndoで戻り、pointercancel後はほかの目玉を変えない', async ({ page }) => {
  const eyes = tree(page).locator('button[aria-pressed]')
  const first = eyes.nth(0), second = eyes.nth(1)
  const a = (await first.boundingBox())!, b = (await second.boundingBox())!
  await page.mouse.move(a.x + a.width / 2, a.y + a.height / 2)
  await page.mouse.down()
  await page.mouse.move(b.x + b.width / 2, b.y + b.height / 2)
  await page.mouse.up()
  await expect(first).toHaveAttribute('aria-pressed', 'false')
  await expect(second).toHaveAttribute('aria-pressed', 'false')
  await tree(page).focus()
  await page.keyboard.press('Control+z')
  await expect(first).toHaveAttribute('aria-pressed', 'true')
  await expect(second).toHaveAttribute('aria-pressed', 'true')
  await first.hover()
  await first.dispatchEvent('mousedown', { button: 0 })
  await page.evaluate(() => window.dispatchEvent(new PointerEvent('pointercancel')))
  await second.hover()
  await expect(first).toHaveAttribute('aria-pressed', 'false')
  await expect(second).toHaveAttribute('aria-pressed', 'true')
})

