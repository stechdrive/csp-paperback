import { expect, test } from '@playwright/test'

for (const viewport of [{ width: 960, height: 640 }, { width: 1280, height: 820 }]) {
  test(`中央表示の切替で右ペインを動かさず、仮想セルの編集場所を確保する（${viewport.width}px）`, async ({ page }, testInfo) => {
    await page.setViewportSize(viewport)
    const errors: string[] = []
    page.on('pageerror', error => errors.push(error.message))
    await page.goto('./')
    await expect(page.getByTestId('virtual-panel')).toBeHidden()
    await page.getByRole('button', { name: 'サンプルデータで試す', exact: true }).click()
    const output = page.getByTestId('output-view')
    await expect(output).toBeVisible()
    const toolbar = page.locator('[aria-label="プレビューと出力の操作"]')
    const filename = toolbar.locator('[class*="_statusLabel_"]')
    await expect(filename).toHaveText('c001.clip')
    await expect(toolbar.getByRole('button', { name: 'ファイルと処理状況' })).toHaveCount(0)
    await filename.click()
    await expect(page.locator('#toolbar-status')).toHaveCount(0)
    await page.evaluate(() => document.fonts.ready)
    expect((await output.boundingBox())!.height).toBeGreaterThan(viewport.height - 150)
    const source = page.getByTestId('source-panel')
    const sourceBefore = await source.boundingBox()
    const navBefore = await page.getByTestId('navigator-panel').boundingBox()
    expect(navBefore!.height).toBe(200)
    const treeBounds = (await page.getByTestId('layer-tree').boundingBox())!
    // The persistent output/source headings add one compact row.
    expect(treeBounds.height).toBeGreaterThan(viewport.height - 370)
    const layerFooter = (await page.getByTestId('layer-panel-footer').boundingBox())!
    const switchBounds = (await page.getByRole('group', { name: 'レイヤーパネルの表示' }).boundingBox())!
    expect(Math.abs(switchBounds.y + switchBounds.height / 2 - layerFooter.y - layerFooter.height / 2)).toBeLessThan(1)
    await expect(source.getByText('Shift+スクロールで切替', { exact: true })).toBeVisible()
    const previewBounds = (await output.boundingBox())!
    expect((await page.locator('[class*="_outputSection_"]').boundingBox())!.y).toBe(previewBounds.y)
    const timeline = source.getByRole('slider', { name: 'タイムラインのフレーム' })
    const timelineBefore = await timeline.boundingBox()

    await page.getByRole('button', { name: '全体ナビゲーター', exact: true }).click()
    const mainNav = page.getByTestId('navigator-view')
    await expect(mainNav).toBeVisible()
    await expect(output).toBeHidden()
    expect(await source.boundingBox()).toEqual(sourceBefore)
    expect(await page.getByTestId('navigator-panel').boundingBox()).toEqual(navBefore)
    expect(await timeline.boundingBox()).toEqual(timelineBefore)
    const canvas = mainNav.locator('canvas')
    await expect.poll(() => canvas.evaluate(el => el.width)).toBeGreaterThan(1)
    await canvas.hover()
    await page.mouse.wheel(0, -100)
    await expect(canvas).not.toHaveCSS('transform', 'matrix(1, 0, 0, 1, 0, 0)')
    const zoom = await canvas.evaluate(el => el.style.transform)
    await page.getByRole('button', { name: '出力プレビュー', exact: true }).click()
    await page.getByRole('button', { name: '全体ナビゲーター', exact: true }).click()
    expect(await canvas.evaluate(el => el.style.transform)).toBe(zoom)
    await timeline.focus()
    await page.keyboard.press('End')
    expect(Number(await timeline.getAttribute('aria-valuenow'))).toBe(Number(await timeline.getAttribute('aria-valuemax')))

    await page.getByRole('button', { name: '仮想セル', exact: true }).click()
    const virtual = page.getByTestId('virtual-panel')
    await expect(virtual).toBeVisible()
    expect((await source.boundingBox())!.width).toBeLessThanOrEqual(sourceBefore!.width)
    expect((await mainNav.boundingBox())!.width).toBeGreaterThanOrEqual(300)
    await virtual.getByRole('textbox', { name: '新規仮想セル' }).click()
    const memo = source.locator('[data-layer-id]').filter({ has: page.getByText('memo', { exact: true }) }).first()
    await memo.dragTo(virtual.getByText('＋ レイヤーをドロップして追加', { exact: true }))
    await expect(virtual.getByText('memo', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: '出力プレビュー', exact: true }).click()
    await expect(output.locator('canvas').first()).toBeVisible()
    const outputBefore = await output.boundingBox()
    await page.getByRole('button', { name: '書き出し設定', exact: true }).click()
    const settings = page.getByRole('dialog', { name: '書き出し設定', exact: true })
    await expect(settings).toBeVisible()
    expect(await output.boundingBox()).toEqual(outputBefore)
    await settings.getByRole('button', { name: 'PNG', exact: true }).click()
    await page.keyboard.press('Escape')
    await expect(settings).toHaveCount(0)
    await expect(page.getByRole('button', { name: '書き出し設定', exact: true })).toBeFocused()
    await page.getByRole('button', { name: '仮想セルを閉じる' }).click()
    await expect(virtual).toBeHidden()
    expect(await source.boundingBox()).toEqual(sourceBefore)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: testInfo.outputPath('workspace.png') })
    // The useful error details remain available after removing the idle filename popup.
    await page.locator('input[type=file][multiple]').setInputFiles({ name: 'broken.clip', mimeType: 'application/octet-stream', buffer: Buffer.from('invalid clip') })
    const errorDetails = toolbar.getByRole('button', { name: 'エラーの詳細' })
    await expect(errorDetails).toBeVisible()
    await errorDetails.click()
    await expect(page.locator('#toolbar-status')).toContainText(await errorDetails.innerText())
    await expect(page.locator('#toolbar-status')).toContainText('c001.clip')
    await page.locator('input[type=file][multiple]').setInputFiles('public/sample/c001.clip')
    await expect(errorDetails).toHaveCount(0)
    await expect(page.locator('#toolbar-status')).toHaveCount(0)
    expect(errors).toEqual([])
  })
}

test('長いファイル名と複数出力は下端から確認でき、画像と設定ボタンを動かさない', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 960, height: 640 })
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('./')
  await page.getByRole('button', { name: 'サンプルデータで試す', exact: true }).click()
  const name = page.getByTestId('preview-file-name')
  await expect(name).toHaveText('仮想セルテスト.jpg')
  await page.evaluate(() => document.fonts.ready)
  const output = page.getByTestId('output-view')
  const before = await output.boundingBox()
  const footer = page.getByTestId('preview-footer')
  const footerBefore = await footer.boundingBox()
  const settings = page.getByRole('button', { name: '書き出し設定', exact: true })
  const settingsBefore = await settings.boundingBox()

  await page.getByRole('button', { name: '仮想セル', exact: true }).click()
  const longName = '背景原図とキャラクターのレイアウト_' + '長いファイル名'.repeat(8)
  await page.getByTestId('virtual-panel').locator('input[value="仮想セルテスト"]').fill(longName)
  await page.getByRole('button', { name: '仮想セルを閉じる' }).click()
  await expect(name).toHaveText(`${longName}.jpg`)
  expect(await name.evaluate(element => element.scrollWidth > element.clientWidth)).toBe(true)
  expect(await output.boundingBox()).toEqual(before)
  expect(await footer.boundingBox()).toEqual(footerBefore)
  expect(await settings.boundingBox()).toEqual(settingsBefore)
  await page.getByRole('button', { name: 'プレビュー中のファイル名（1件）', exact: true }).click()
  const names = page.getByRole('dialog', { name: 'プレビュー中のファイル名', exact: true })
  await expect(names.getByRole('listitem')).toHaveText([`${longName}.jpg`])
  expect(await output.boundingBox()).toEqual(before)
  await page.keyboard.press('Escape')
  await expect(names).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'プレビュー中のファイル名（1件）', exact: true })).toBeFocused()

  const mode = page.getByRole('group', { name: 'レイヤーパネルの表示' })
  await mode.getByRole('button', { name: '出力一覧', exact: true }).click()
  await page.getByRole('option', { name: 'B_1.jpg', exact: true }).click()
  await page.getByRole('button', { name: '選択中の出力をツリーで表示' }).click()
  await page.getByRole('listbox', { name: '出力ファイル' }).getByRole('option', { name: 'B_1_s.jpg', exact: true }).click({ modifiers: ['Control'] })
  await page.getByRole('button', { name: '選択項目を並べて表示' }).click()
  await expect(output.locator('canvas')).toHaveCount(2)
  const files = page.getByRole('button', { name: 'プレビュー中のファイル名（2件）', exact: true })
  await expect(files).toContainText('2件')
  expect(await output.boundingBox()).toEqual(before)
  expect(await footer.boundingBox()).toEqual(footerBefore)
  expect(await settings.boundingBox()).toEqual(settingsBefore)
  await files.click()
  await expect(names.getByRole('listitem')).toHaveText(['B_1.jpg', 'B_1_s.jpg'])
  expect(await output.boundingBox()).toEqual(before)
  await page.screenshot({ path: testInfo.outputPath('preview-files.png') })
  await settings.click()
  await expect(names).toHaveCount(0)
  await expect(page.getByRole('dialog', { name: '書き出し設定', exact: true })).toBeVisible()
  expect(await output.boundingBox()).toEqual(before)
  await page.keyboard.press('Escape')

  const navigator = page.getByTestId('navigator-panel')
  const resize = page.getByTitle('ナビゲーターの高さを変更')
  const handle = (await resize.boundingBox())!
  await page.mouse.move(handle.x + handle.width / 2, handle.y + handle.height / 2)
  await page.mouse.down()
  await page.mouse.move(handle.x + handle.width / 2, handle.y + handle.height / 2 + 40)
  await page.mouse.up()
  expect((await navigator.boundingBox())!.height).toBe(240)
  const resized = await navigator.boundingBox()
  await page.getByRole('button', { name: '全体ナビゲーター', exact: true }).click()
  expect(await navigator.boundingBox()).toEqual(resized)
  expect(await footer.boundingBox()).toEqual(footerBefore)
  expect(await settings.boundingBox()).toEqual(settingsBefore)
  await page.getByRole('button', { name: '出力プレビュー', exact: true }).click()
  expect(await navigator.boundingBox()).toEqual(resized)
  expect(await output.boundingBox()).toEqual(before)
  expect(errors).toEqual([])
})

test.describe('幅320pxの操作', () => {
  test.use({ viewport: { width: 320, height: 640 }, hasTouch: true, isMobile: true })
  test('表示サイズ変更とパネル切替後も設定とプレビューへ戻れる', async ({ page }) => {
    await page.goto('./')
    await page.getByRole('button', { name: 'サンプルデータで試す', exact: true }).click()
    await page.getByRole('button', { name: 'メニュー', exact: true }).click()
    const initialSize = await page.evaluate(() => getComputedStyle(document.documentElement).fontSize)
    await page.locator('#toolbar-ui-scale').fill('200')
    expect(await page.evaluate(() => getComputedStyle(document.documentElement).fontSize)).not.toBe(initialSize)
    await page.keyboard.press('Escape')
    const toolbarBounds = await page.locator('[aria-label="プレビューと出力の操作"] button:visible').evaluateAll(buttons => buttons.map(button => button.getBoundingClientRect().right))
    expect(Math.max(...toolbarBounds)).toBeLessThanOrEqual(320)
    await page.getByRole('button', { name: '全体ナビゲーター', exact: true }).click()
    await expect(page.getByTestId('navigator-view')).toBeVisible()
    await expect(page.getByTestId('navigator-view').getByRole('slider')).toBeVisible()
    await page.getByRole('navigation', { name: '作業パネル' }).getByRole('button', { name: '仮想セル' }).click()
    await expect(page.getByTestId('virtual-panel')).toBeVisible()
    await page.getByRole('button', { name: '仮想セルを閉じる' }).click()
    await expect(page.getByTestId('navigator-view')).toBeVisible()
    await page.getByRole('navigation', { name: '作業パネル' }).getByRole('button', { name: 'レイヤー' }).click()
    const opacity = page.getByTestId('source-panel').getByRole('button', { name: /^不透明度/ })
    const valueBox = (await opacity.getByText('100%', { exact: true }).boundingBox())!
    const opacityBox = (await opacity.boundingBox())!
    expect(valueBox.x + valueBox.width).toBeLessThanOrEqual(opacityBox.x + opacityBox.width)
    const switcher = page.getByTestId('layer-panel-footer').getByRole('group', { name: 'レイヤーパネルの表示' })
    await switcher.getByRole('button', { name: '出力一覧', exact: true }).tap()
    await expect(page.getByRole('listbox', { name: '出力ファイル' })).toBeVisible()
    await switcher.getByRole('button', { name: 'レイヤー', exact: true }).tap()
    await expect(page.getByTestId('layer-tree')).toBeVisible()
    await page.getByRole('button', { name: '出力プレビュー', exact: true }).click()
    const previewBefore = await page.getByTestId('output-view').boundingBox()
    await page.getByRole('button', { name: /^プレビュー中のファイル名/ }).tap()
    const filenames = page.getByRole('dialog', { name: 'プレビュー中のファイル名', exact: true })
    await expect(filenames).toBeVisible()
    const filenameBox = (await filenames.boundingBox())!
    expect(filenameBox.x).toBeGreaterThanOrEqual(0)
    expect(filenameBox.x + filenameBox.width).toBeLessThanOrEqual(320)
    expect(await page.getByTestId('output-view').boundingBox()).toEqual(previewBefore)
    await filenames.getByRole('button', { name: 'ファイル名を閉じる' }).tap()
    await page.getByRole('button', { name: '全体ナビゲーター', exact: true }).click()
    await page.getByRole('button', { name: '書き出し設定', exact: true }).click()
    const settings = page.getByRole('dialog', { name: '書き出し設定', exact: true })
    await expect(settings).toBeVisible()
    const box = (await settings.boundingBox())!
    expect(box.x).toBeGreaterThanOrEqual(0)
    expect(box.x + box.width).toBeLessThanOrEqual(320)
    expect(box.y).toBeGreaterThanOrEqual(0)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  })
})
