import { expect, test } from '@playwright/test'

for (const viewport of [{ width: 960, height: 640 }, { width: 1280, height: 820 }]) {
  test(`中央表示の切替で右ペインを動かさず、仮想セルの編集場所を確保する（${viewport.width}px）`, async ({ page }, testInfo) => {
    await page.setViewportSize(viewport)
    const errors: string[] = []
    page.on('pageerror', error => errors.push(error.message))
    await page.goto('./')
    await expect(page.getByTestId('virtual-panel')).toBeHidden()
    await page.getByRole('button', { name: 'サンプルデータで試す', exact: true }).click()
    const output = page.getByTestId('output-view')
    await expect(output).toBeVisible()
    await page.evaluate(() => document.fonts.ready)
    expect((await output.boundingBox())!.height).toBeGreaterThan(viewport.height - 150)
    const source = page.getByTestId('source-panel')
    const sourceBefore = await source.boundingBox()
    const navBefore = await page.getByTestId('navigator-panel').boundingBox()
    const timeline = source.getByRole('slider', { name: 'タイムラインのフレーム' })
    const timelineBefore = await timeline.boundingBox()

    await page.getByRole('button', { name: '全体ナビゲーター', exact: true }).click()
    const mainNav = page.getByTestId('navigator-view')
    await expect(mainNav).toBeVisible()
    await expect(output).toBeHidden()
    expect(await source.boundingBox()).toEqual(sourceBefore)
    expect(await page.getByTestId('navigator-panel').boundingBox()).toEqual(navBefore)
    expect(await timeline.boundingBox()).toEqual(timelineBefore)
    const canvas = mainNav.locator('canvas')
    await expect.poll(() => canvas.evaluate(el => el.width)).toBeGreaterThan(1)
    await canvas.hover()
    await page.mouse.wheel(0, -100)
    await expect(canvas).not.toHaveCSS('transform', 'matrix(1, 0, 0, 1, 0, 0)')
    const zoom = await canvas.evaluate(el => el.style.transform)
    await page.getByRole('button', { name: '出力プレビュー', exact: true }).click()
    await page.getByRole('button', { name: '全体ナビゲーターを中央で大きく表示' }).click()
    expect(await canvas.evaluate(el => el.style.transform)).toBe(zoom)
    await timeline.focus()
    await page.keyboard.press('End')
    expect(Number(await timeline.getAttribute('aria-valuenow'))).toBe(Number(await timeline.getAttribute('aria-valuemax')))

    await page.getByRole('button', { name: '仮想セル', exact: true }).click()
    const virtual = page.getByTestId('virtual-panel')
    await expect(virtual).toBeVisible()
    expect(await source.boundingBox()).toEqual(sourceBefore)
    expect((await mainNav.boundingBox())!.width).toBeGreaterThan(300)
    await virtual.getByRole('textbox', { name: '新規仮想セル' }).click()
    const memo = source.locator('[data-layer-id]').filter({ has: page.getByText('memo', { exact: true }) }).first()
    await memo.dragTo(virtual.getByText('＋ レイヤーをドロップして追加', { exact: true }))
    await expect(virtual.getByText('memo', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: '出力プレビュー', exact: true }).click()
    await expect(output.locator('canvas').first()).toBeVisible()
    const outputBefore = await output.boundingBox()
    await page.getByRole('button', { name: '書き出し設定', exact: true }).click()
    const settings = page.getByRole('dialog', { name: '書き出し設定', exact: true })
    await expect(settings).toBeVisible()
    expect(await output.boundingBox()).toEqual(outputBefore)
    await settings.getByRole('button', { name: 'PNG', exact: true }).click()
    await page.keyboard.press('Escape')
    await expect(settings).toHaveCount(0)
    await expect(page.getByRole('button', { name: '書き出し設定', exact: true })).toBeFocused()
    await page.getByRole('button', { name: '仮想セルを閉じる' }).click()
    await expect(virtual).toBeHidden()
    expect(await source.boundingBox()).toEqual(sourceBefore)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: testInfo.outputPath('workspace.png') })
    expect(errors).toEqual([])
  })
}

test.describe('幅320pxの操作', () => {
  test.use({ viewport: { width: 320, height: 640 }, hasTouch: true, isMobile: true })
  test('表示サイズ変更とパネル切替後も設定とプレビューへ戻れる', async ({ page }) => {
    await page.goto('./')
    await page.getByRole('button', { name: 'サンプルデータで試す', exact: true }).click()
    await page.getByRole('button', { name: 'メニュー', exact: true }).click()
    const initialSize = await page.evaluate(() => getComputedStyle(document.documentElement).fontSize)
    await page.locator('#toolbar-ui-scale').fill('200')
    expect(await page.evaluate(() => getComputedStyle(document.documentElement).fontSize)).not.toBe(initialSize)
    await page.keyboard.press('Escape')
    const toolbarBounds = await page.locator('[aria-label="プレビューと出力の操作"] button:visible').evaluateAll(buttons => buttons.map(button => button.getBoundingClientRect().right))
    expect(Math.max(...toolbarBounds)).toBeLessThanOrEqual(320)
    await page.getByRole('button', { name: '全体ナビゲーター', exact: true }).click()
    await expect(page.getByTestId('navigator-view')).toBeVisible()
    await expect(page.getByTestId('navigator-view').getByRole('slider')).toBeVisible()
    await page.getByRole('navigation', { name: '作業パネル' }).getByRole('button', { name: '仮想セル' }).click()
    await expect(page.getByTestId('virtual-panel')).toBeVisible()
    await page.getByRole('button', { name: '仮想セルを閉じる' }).click()
    await expect(page.getByTestId('navigator-view')).toBeVisible()
    await page.getByRole('navigation', { name: '作業パネル' }).getByRole('button', { name: 'レイヤー' }).click()
    const opacity = page.getByTestId('source-panel').getByRole('button', { name: /^不透明度/ })
    const valueBox = (await opacity.getByText('100%', { exact: true }).boundingBox())!
    const opacityBox = (await opacity.boundingBox())!
    expect(valueBox.x + valueBox.width).toBeLessThanOrEqual(opacityBox.x + opacityBox.width)
    await page.getByRole('button', { name: '全体ナビゲーター', exact: true }).click()
    await page.getByRole('button', { name: '書き出し設定', exact: true }).click()
    const settings = page.getByRole('dialog', { name: '書き出し設定', exact: true })
    await expect(settings).toBeVisible()
    const box = (await settings.boundingBox())!
    expect(box.x).toBeGreaterThanOrEqual(0)
    expect(box.x + box.width).toBeLessThanOrEqual(320)
    expect(box.y).toBeGreaterThanOrEqual(0)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  })
})
